package hva.core;

public abstract class hotelEntity {
    private String id;
    private String name;
    private Hotel _hotel;

    public hotelEntity(String id, String name) {
        this.id = id;
        this.name = name;
    }

    public String getId() {
        return id;
    }

    public String getName() {
        return name;
    }

    public void setId(String id) {
        this.id = id;
    }

    public void setName(String name) {
        this.name = name;
    }
}